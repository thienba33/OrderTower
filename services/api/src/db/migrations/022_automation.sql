-- Migration 022: automation runtime, notification và retry cho outbox.
-- automation_runs là nhật ký job (scheduler hoặc chạy tay); notifications là
-- hộp thư theo vai/user. Outbox thêm max_attempts + next_attempt_at để job
-- relay retry có backoff thay vì đánh failed ngay.

ALTER TABLE outbox_events
  ADD COLUMN IF NOT EXISTS max_attempts INTEGER NOT NULL DEFAULT 5;
ALTER TABLE outbox_events
  ADD COLUMN IF NOT EXISTS next_attempt_at TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS idx_outbox_events_due
  ON outbox_events (status, next_attempt_at);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id TEXT NOT NULL DEFAULT 'default',
  type TEXT NOT NULL,
  title TEXT NOT NULL,
  body TEXT NOT NULL,
  entity_type TEXT,
  entity_id TEXT,
  action_href TEXT,
  audience_role TEXT,
  audience_user TEXT,
  dedup_key TEXT,
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

-- NULL được phép lặp; chỉ notification tự động có dedup_key mới chống trùng.
CREATE UNIQUE INDEX IF NOT EXISTS ux_notifications_dedup
  ON notifications (dedup_key);
CREATE INDEX IF NOT EXISTS idx_notifications_audience_read
  ON notifications (tenant_id, audience_role, read_at);
CREATE INDEX IF NOT EXISTS idx_notifications_created
  ON notifications (created_at);

CREATE TABLE IF NOT EXISTS automation_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id TEXT NOT NULL DEFAULT 'default',
  job_name TEXT NOT NULL,
  trigger TEXT NOT NULL,
  status TEXT NOT NULL,
  started_at TIMESTAMPTZ NOT NULL,
  finished_at TIMESTAMPTZ NOT NULL,
  duration_ms INTEGER NOT NULL,
  summary JSONB NOT NULL DEFAULT '{}'::jsonb,
  error TEXT,
  PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_automation_runs_job_started
  ON automation_runs (job_name, started_at);
