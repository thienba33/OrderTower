-- Migration 002: bảng lưu bền cho shipment và lịch sử chuyển trạng thái.
-- Khóa chính viết ở cuối bảng (PRIMARY KEY (...)) thay vì viết ngay sau cột,
-- để câu lệnh chạy được cả trên Postgres thật và trên pg-mem dùng kiểm thử.
-- Không dùng JSONB ở đây: mọi trường của shipment đều là chuỗi hoặc null.
-- Ghi chú về pg-mem: CREATE TABLE IF NOT EXISTS có ràng buộc chạy lần 2
-- trên bảng đã tồn tại sẽ lỗi trong pg-mem 3.0.14 (xem chú thích trong
-- src/db/db.service.ts); runner chỉ chạy mỗi migration 1 lần nên không gặp.

CREATE TABLE IF NOT EXISTS shipments (
  id TEXT NOT NULL,
  order_id TEXT NOT NULL,
  status TEXT NOT NULL,
  driver_id TEXT,
  vehicle_id TEXT,
  proof_photo_key TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_shipments_order_id ON shipments (order_id);
CREATE INDEX IF NOT EXISTS idx_shipments_status ON shipments (status);

CREATE TABLE IF NOT EXISTS shipment_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  shipment_id TEXT NOT NULL REFERENCES shipments (id) ON DELETE CASCADE,
  from_state TEXT,
  to_state TEXT NOT NULL,
  actor TEXT NOT NULL,
  role TEXT NOT NULL,
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);
