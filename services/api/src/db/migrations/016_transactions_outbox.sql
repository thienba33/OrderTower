-- Migration 016: giao dịch order+audit+stock, bộ đếm ID trong DB và outbox.
-- id_counters giữ con trỏ cấp ID nguyên tử cho DH/LS/WF, tránh trùng khi
-- nhiều request/tiến trình. outbox_events ghi sự kiện trong cùng transaction
-- với nghiệp vụ để consumer có thể phát lại an toàn.
-- Unique index workflow instance bảo vệ khỏi tạo trùng businessKey khi
-- nhiều request đồng thời.

CREATE TABLE IF NOT EXISTS id_counters (
  name TEXT NOT NULL,
  value BIGINT NOT NULL,
  PRIMARY KEY (name)
);

CREATE TABLE IF NOT EXISTS outbox_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  event_type TEXT NOT NULL,
  aggregate_type TEXT NOT NULL,
  aggregate_id TEXT NOT NULL,
  payload JSONB NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  attempts INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  processed_at TIMESTAMPTZ,
  last_error TEXT,
  PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_outbox_events_status ON outbox_events (status);
CREATE INDEX IF NOT EXISTS idx_outbox_events_aggregate ON outbox_events (aggregate_type, aggregate_id);

CREATE UNIQUE INDEX IF NOT EXISTS ux_workflow_instances_business_key
  ON workflow_instances (definition_id, business_key);
