-- Migration 001: bảng lưu bền cho audit, workflow instance, phê duyệt,
-- đơn hàng và tồn kho. Mọi bảng đều có created_at/updated_at để đối chiếu.
-- Lưu ý: audit_log có thêm cột at (thời điểm sự kiện) ngoài created_at,
-- vì chuỗi hash của audit tính trên at; inventory có thêm cột name và unit,
-- vì kiểu InventoryItem trong code gồm cả 2 trường này.
-- Khóa chính viết ở cuối bảng (PRIMARY KEY (...)) thay vì viết ngay sau cột,
-- để câu lệnh chạy được cả trên Postgres thật và trên pg-mem dùng kiểm thử.

CREATE TABLE IF NOT EXISTS schema_migrations (
  version TEXT NOT NULL,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (version)
);

CREATE TABLE IF NOT EXISTS audit_log (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  at TIMESTAMPTZ NOT NULL,
  actor TEXT NOT NULL,
  role TEXT NOT NULL,
  action TEXT NOT NULL,
  order_id TEXT,
  from_state TEXT,
  to_state TEXT,
  detail TEXT NOT NULL DEFAULT '',
  prev_hash TEXT NOT NULL,
  hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (seq)
);
CREATE INDEX IF NOT EXISTS idx_audit_log_order_id ON audit_log (order_id);

CREATE TABLE IF NOT EXISTS workflow_instances (
  id TEXT NOT NULL,
  definition_id TEXT NOT NULL,
  definition_version TEXT NOT NULL,
  business_key TEXT NOT NULL,
  current_state TEXT NOT NULL,
  status TEXT NOT NULL,
  context JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_workflow_instances_business_key ON workflow_instances (business_key);
CREATE INDEX IF NOT EXISTS idx_workflow_instances_definition_id ON workflow_instances (definition_id);

CREATE TABLE IF NOT EXISTS workflow_instance_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  instance_id TEXT NOT NULL REFERENCES workflow_instances (id) ON DELETE CASCADE,
  from_state TEXT,
  to_state TEXT NOT NULL,
  actor TEXT NOT NULL,
  role TEXT NOT NULL,
  reason TEXT,
  handling TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS approvals (
  id TEXT NOT NULL,
  type TEXT NOT NULL,
  subject_id TEXT NOT NULL,
  reason TEXT NOT NULL,
  requested_by TEXT NOT NULL,
  requested_at TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL,
  decided_by TEXT,
  decided_at TIMESTAMPTZ,
  decision_reason TEXT,
  applied_at TIMESTAMPTZ,
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_approvals_subject_id ON approvals (subject_id);
CREATE INDEX IF NOT EXISTS idx_approvals_status ON approvals (status);

CREATE TABLE IF NOT EXISTS orders (
  id TEXT NOT NULL,
  idempotency_key TEXT NOT NULL,
  customer TEXT NOT NULL,
  items JSONB NOT NULL,
  state TEXT NOT NULL,
  address JSONB,
  address_trust INTEGER,
  address_level TEXT,
  workflow_instance_id TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  UNIQUE (idempotency_key)
);

CREATE TABLE IF NOT EXISTS order_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  order_id TEXT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  from_state TEXT,
  to_state TEXT NOT NULL,
  actor TEXT NOT NULL,
  role TEXT NOT NULL,
  reason TEXT,
  handling TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS inventory (
  sku TEXT NOT NULL,
  name TEXT NOT NULL,
  unit TEXT NOT NULL,
  stock INTEGER NOT NULL,
  reserved INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (sku)
);
